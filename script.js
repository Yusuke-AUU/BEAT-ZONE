// ===== MIDI NOTE TO FREQUENCY =====
function midiToFreq(m) { return 440 * Math.pow(2, (m - 69) / 12); }
function freq(name) {
  const NOTE_MAP = {C:0,'C#':1,Db:1,D:2,'D#':3,Eb:3,E:4,F:5,'F#':6,Gb:6,G:7,'G#':8,Ab:8,A:9,'A#':10,Bb:10,B:11};
  const m = name.match(/^([A-G][b#]?)(\d)$/);
  if (!m) return 440;
  return Math.round(440 * Math.pow(2, (NOTE_MAP[m[1]] + (parseInt(m[2])+1)*12 - 69)/12) * 100)/100;
}

// ===== AUDIO ENGINE =====
const AudioEngine = (() => {
  let ctx = null, master = null, bgNodes = [];

  function init() {
    if (ctx) return;
    ctx = new (window.AudioContext || window.webkitAudioContext)();
    master = ctx.createGain(); master.gain.value = 0.7;
    master.connect(ctx.destination);
  }
  function resume() { if (ctx && ctx.state==='suspended') ctx.resume(); }
  function now() { return ctx ? ctx.currentTime : 0; }

  function osc(type, f, t, dur, vol) {
    const o=ctx.createOscillator(), g=ctx.createGain();
    o.type=type; o.frequency.value=f;
    o.connect(g); g.connect(master);
    g.gain.setValueAtTime(0.001,t);
    g.gain.linearRampToValueAtTime(vol,t+0.015);
    g.gain.exponentialRampToValueAtTime(0.001,t+dur);
    o.start(t); o.stop(t+dur+0.05);
    bgNodes.push(o,g);
  }

  function noiseN(t, dur, vol, hpf, lpf) {
    const len=Math.ceil(ctx.sampleRate*Math.max(dur,0.02));
    const buf=ctx.createBuffer(1,len,ctx.sampleRate);
    const d=buf.getChannelData(0);
    for(let i=0;i<len;i++) d[i]=Math.random()*2-1;
    const src=ctx.createBufferSource(); src.buffer=buf;
    const g=ctx.createGain();
    const hp=ctx.createBiquadFilter(); hp.type='highpass'; hp.frequency.value=hpf||0;
    const lp=ctx.createBiquadFilter(); lp.type='lowpass'; lp.frequency.value=lpf||20000;
    g.gain.setValueAtTime(vol,t); g.gain.exponentialRampToValueAtTime(0.001,t+dur);
    src.connect(hp); hp.connect(lp); lp.connect(g); g.connect(master);
    src.start(t); src.stop(t+dur+0.02);
    bgNodes.push(src,g,hp,lp);
  }

  function kick(t,vol) {
    const o=ctx.createOscillator(),g=ctx.createGain();
    o.frequency.setValueAtTime(150,t); o.frequency.exponentialRampToValueAtTime(0.001,t+0.4);
    g.gain.setValueAtTime(vol||0.6,t); g.gain.exponentialRampToValueAtTime(0.001,t+0.4);
    o.connect(g); g.connect(master); o.start(t); o.stop(t+0.45);
    bgNodes.push(o,g);
  }
  function snare(t,vol) { noiseN(t,0.14,vol||0.20,1500,8000); osc('triangle',200,t,0.1,(vol||0.20)*0.5); }
  function hat(t,vol,open) { noiseN(t,open?0.18:0.03,vol||0.07,9000,18000); }
  function clap(t,vol) { for(let i=0;i<3;i++) noiseN(t+i*0.01,0.06,vol||0.18,2000,10000); }

  function hitNote(f, instrument) {
    if(!ctx) return; resume();
    const t=ctx.currentTime;
    switch(instrument) {
      case 'piano':
        osc('triangle',f,t,0.7,0.30); osc('sine',f*2,t,0.35,0.12); osc('sine',f*3,t,0.18,0.05); break;
      case 'synth':
        osc('sawtooth',f,t,0.4,0.22); osc('sawtooth',f*1.004,t,0.4,0.18); osc('square',f*0.5,t,0.25,0.06); break;
      case 'electric':
        osc('sawtooth',f,t,0.35,0.20); osc('sine',f,t,0.35,0.12); osc('sine',f*2,t,0.2,0.08); break;
      default:
        osc('triangle',f,t,0.5,0.25); osc('sine',f*2,t,0.25,0.10);
    }
  }
  function hitMiss() { if(!ctx) return; noiseN(ctx.currentTime,0.06,0.05,0,1500); }

  function playBG(song, startT, duration) {
    if(!ctx) return;
    const beat=60/song.bpm, bar=beat*4;
    const bars=Math.ceil(duration/bar)+2;
    const genre=song.genre;

    for(let b=0;b<bars;b++) {
      const t=startT+b*bar;
      if(genre==='classic') {
        kick(t,0.35); kick(t+beat*2,0.28);
        snare(t+beat,0.14); snare(t+beat*3,0.14);
        for(let k=0;k<8;k++) hat(t+k*beat*0.5,0.06);
      } else if(genre==='electronic' || genre==='dance') {
        kick(t,0.70); kick(t+beat,0.55); kick(t+beat*2,0.70); kick(t+beat*3,0.55);
        snare(t+beat,0.22); snare(t+beat*3,0.22);
        clap(t+beat,0.18); clap(t+beat*3,0.18);
        for(let k=0;k<16;k++) hat(t+k*beat*0.25,k%4===0?0.10:0.06);
      } else if(genre==='latin') {
        kick(t,0.60); kick(t+beat*0.75,0.45); kick(t+beat*2,0.60); kick(t+beat*2.75,0.45);
        snare(t+beat,0.20); snare(t+beat*3,0.20);
        clap(t+beat*0.5,0.12); clap(t+beat*2.5,0.12);
        for(let k=0;k<8;k++) hat(t+k*beat*0.5,0.08);
      } else { // pop
        kick(t,0.60); kick(t+beat*2,0.50);
        snare(t+beat,0.20); snare(t+beat*3,0.20);
        clap(t+beat,0.16); clap(t+beat*3,0.16);
        for(let k=0;k<8;k++) hat(t+k*beat*0.5,0.07);
      }
      // Bass line - root notes per bar
      const bassFreqs={'classic':130.81,'electronic':87.31,'dance':110,'latin':87.31,'pop':110};
      const bf=bassFreqs[genre]||110;
      osc('sine',bf,t,beat*1.8,0.28); osc('sawtooth',bf,t,beat*0.9,0.10);
      osc('sine',bf,t+beat*2,beat*1.8,0.22); osc('sawtooth',bf,t+beat*2,beat*0.9,0.08);
    }
  }

  function stopAll() {
    bgNodes.forEach(n=>{try{n.stop?n.stop():n.disconnect();}catch(e){}});
    bgNodes=[];
  }

  return {init,resume,now,hitNote,hitMiss,playBG,stopAll};
})();

// ===== DIFFICULTY FILTER =====
function filterChart(rawNotes, difficulty) {
  if(difficulty==='hard') return rawNotes;

  // Split by lane and filter independently
  const byLane=[[],[],[]];
  rawNotes.forEach(n=>byLane[n.l].push(n));

  const result=[];
  byLane.forEach((laneNotes,li)=>{
    const step = difficulty==='easy' ? (li===2?2:3) : 2;
    laneNotes.forEach((n,i)=>{ if(i%step===0) result.push(n); });
  });

  result.sort((a,b)=>a.t-b.t);
  const clean=[];
  let lastT=-999;
  result.forEach(n=>{
    if(n.t-lastT>=0.10){clean.push(n);lastT=n.t;}
  });
  return clean;
}

